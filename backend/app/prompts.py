def build_document_user_prompt(req: DocumentRequest) -> str:
    template = (
        _discharge_template(has_procedure=bool(req.procedure.strip()))
        if req.doc_type == "discharge_summary"
        else DOC_TEMPLATES[req.doc_type]
    )
    parts = [template, "Дані від лікаря:"]
    for field, label in _FIELD_LABELS:
        value = getattr(req, field, "") or ""
        if value.strip():
            parts.append(f"- {label}: {value.strip()}")
    if req.doc_type == "discharge_summary":
        parts.append("")
        parts.append(_TYPICAL_RECS_ON if req.typical_recommendations else _TYPICAL_RECS_OFF)
    return "\n".join(parts)
