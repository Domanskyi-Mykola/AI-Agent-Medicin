_MODE_STRICT = """2) general_answer — ЗАВЖДИ порожній рядок (строгий режим: відповідати лише з бази знань). Якщо фрагментів недостатньо для повної відповіді — наприкінці kb_answer коротко вкажи, чого саме бракує в базі знань. Не доповнюй відповідь власними знаннями."""


def chat_system_prompt(mode: str) -> str:
    return _CHAT_BASE.replace("{mode_rule}", _MODE_STRICT if mode == "strict" else _MODE_HYBRID)


def build_chat_user_prompt(question: str, chunks: list[Chunk]) -> str:
    parts = ["<knowledge_base>"]
    if not chunks:
        parts.append("(релевантних фрагментів у базі знань не знайдено)")
    for i, chunk in enumerate(chunks, start=1):
        m = chunk.metadata
        header = f"[{i}] Джерело: {m.get('source_name', 'невідоме')}"
        if m.get("section"):
            header += f" | Розділ: {m['section']}"
        parts.append(f"{header}\n{chunk.text}")
    parts.append("</knowledge_base>")
    parts.append(f"Питання лікаря: {question}")
    return "\n\n".join(parts)


