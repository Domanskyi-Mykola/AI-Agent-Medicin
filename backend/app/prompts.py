    # операції, якої не було.
    treatment = (
        "## Проведене лікування та втручання — якщо серед переданого було оперативне "
        "втручання, додай рядок «Дата операції: {{OPERATION_DATE}}» дослівно з токеном\n"
        if has_procedure
        else "## Проведене лікування та втручання\n"
    )
    return (
        "Склади чернетку ВИПИСНОГО ЕПІКРИЗУ. Почни із заголовка «# ВИПИСНИЙ ЕПІКРИЗ», далі розділи:\n"
        "## Паспортна частина — встав РІВНО ці рядки з токенами дослівно (правило 4), нічого не змінюючи:\n"
        f"{PASSPORT_PLACEHOLDER_BLOCK}"
        "## Заключний клінічний діагноз\n"
        "## Скарги та анамнез при госпіталізації\n"
        "## Об'єктивний стан і дані обстежень при госпіталізації\n"
        f"{treatment}"
        "## Перебіг захворювання\n"
        "## Стан при виписці\n"
        "## Рекомендації\n"
    )


