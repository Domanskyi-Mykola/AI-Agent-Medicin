def build_document_user_prompt(req: DocumentRequest) -> str:
    template = DOC_TEMPLATES[req.doc_type]
    parts = [
        template,
        "Дані від лікаря:",
        f"- Діагноз: {req.diagnosis}",
    ]
    if req.procedure.strip():
        parts.append(f"- Втручання/процедури: {req.procedure}")
    if req.notes.strip():
        parts.append(f"- Перебіг та примітки: {req.notes}")
    return "\n".join(parts)
